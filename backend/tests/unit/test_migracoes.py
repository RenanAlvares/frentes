"""Migrations e backup pré-migração (06 §5, RN-112)."""

import os
import sqlite3
from contextlib import closing
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import pytest
from alembic import command

from app.db.migracoes import caminho_sqlite, config_alembic, fazer_backup

AGORA = datetime(2026, 10, 14, 9, 5, tzinfo=ZoneInfo("America/Sao_Paulo"))


def test_upgrade_head_em_banco_vazio_sem_diferencas_para_os_modelos(tmp_path: Path) -> None:
    cfg = config_alembic(f"sqlite:///{(tmp_path / 'frentes.db').as_posix()}")

    command.upgrade(cfg, "head")

    # Equivale a `alembic check`: lança AutogenerateDiffsDetected se modelo e banco divergirem.
    command.check(cfg)


def test_rn112_backup_mantem_os_5_mais_recentes(tmp_path: Path) -> None:
    banco = tmp_path / "frentes.db"
    banco.write_bytes(b"")
    pasta = tmp_path / "backups"
    pasta.mkdir()
    for indice in range(6):
        antigo = pasta / f"pre-migracao-r{indice}-2026-01-0{indice + 1}-0000.db"
        antigo.write_bytes(b"")
        os.utime(antigo, (1_000_000 + indice, 1_000_000 + indice))
    outro = pasta / "frentes-backup-2026-01-01-0000.zip"
    outro.write_bytes(b"")
    os.utime(outro, (1, 1))

    destino = fazer_backup(banco, pasta, "abc123", AGORA)

    assert destino.name == "pre-migracao-abc123-2026-10-14-0905.db"
    assert sorted(arquivo.name for arquivo in pasta.glob("pre-migracao-*.db")) == [
        "pre-migracao-abc123-2026-10-14-0905.db",
        "pre-migracao-r2-2026-01-03-0000.db",
        "pre-migracao-r3-2026-01-04-0000.db",
        "pre-migracao-r4-2026-01-05-0000.db",
        "pre-migracao-r5-2026-01-06-0000.db",
    ]
    assert outro.exists()


def test_rn112_backup_inclui_dados_ainda_no_wal(tmp_path: Path) -> None:
    banco = tmp_path / "frentes.db"
    with closing(sqlite3.connect(banco)) as aberta:
        aberta.execute("PRAGMA journal_mode = WAL")
        aberta.execute("CREATE TABLE t (x INTEGER)")
        aberta.execute("INSERT INTO t VALUES (42)")
        aberta.commit()
        # Conexão ainda aberta: os dados estão no -wal, não no arquivo principal.
        destino = fazer_backup(banco, tmp_path, None, AGORA)

    assert destino.name == "pre-migracao-base-2026-10-14-0905.db"
    with closing(sqlite3.connect(destino)) as copia:
        assert copia.execute("SELECT x FROM t").fetchall() == [(42,)]


@pytest.mark.parametrize(
    ("url", "esperado"),
    [
        ("sqlite:///C:/dados/frentes.db", Path("C:/dados/frentes.db")),
        ("sqlite://", None),
        ("sqlite:///:memory:", None),
        ("postgresql://usuario@localhost/frentes", None),
    ],
)
def test_caminho_sqlite(url: str, esperado: Path | None) -> None:
    assert caminho_sqlite(url) == esperado
